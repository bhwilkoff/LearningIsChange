#!/usr/bin/env node
// Voice corpus for BEN.md (the writing bible).
//
//   node scripts/build-voice-corpus.js            dry run: prints the stats
//   node scripts/build-voice-corpus.js --apply    writes docs/voice/{typewriter-transcripts.md,stats.md}
//
// Runs on every render, so a new typewritten page (once OCR'd) and every
// new essay fold into the corpus without anyone doing anything:
//   docs/voice/typewriter-transcripts.md — every OCR/edited transcript, newest first
//   docs/voice/stats.md                  — the measured habits BEN.md cites
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadAllPosts } from './lib/shell.js';
import { bodyText, plainText, dates } from './lib/core.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APPLY = process.argv.includes('--apply');
const OUT = path.join(ROOT, 'docs', 'voice');

const posts = loadAllPosts().filter((p) => !p.removed && p.status !== 'draft');

// ---- transcripts -------------------------------------------------------------
const typed = posts.filter((p) => p.transcript).sort((a, b) => String(b.date_published).localeCompare(String(a.date_published)));
const transcripts = `# Typewritten pages — transcripts

${typed.length} pages, ${typed.reduce((n, p) => n + String(p.transcript).split(/\s+/).length, 0).toLocaleString()} words. Generated by \`scripts/build-voice-corpus.js\` from the \`transcript\` field on each post (OCR, or edited in LiC Admin — see \`transcript_source\`). Typos are the page's own unless marked reviewed.

${typed.map((p) => `## ${p.title} — ${dates(p).dateOnly}\n\n<https://learningischange.com${p.url}> · ${p.transcript_source === 'edited' ? 'reviewed' : `OCR (${p.transcript_source || 'unknown'})`}\n\n${String(p.transcript).trim()}\n`).join('\n')}`;

// ---- stats -----------------------------------------------------------------------
const essays = posts.filter((p) => bodyText(p).split(' ').length >= 250);
const sentsOf = (t) => t.split(/(?<=[.!?])\s+(?=[A-Z"“(])/).map((s) => s.trim()).filter((s) => s.length > 1);
const all = essays.flatMap((p) => sentsOf(bodyText(p)));
const lens = all.map((s) => s.split(' ').length).sort((a, b) => a - b);
const pct = (i) => lens[Math.floor(lens.length * i)];
const text = essays.map(bodyText).join(' ');
const words = text.split(' ').length;
const per1k = (re) => ((text.match(re) || []).length * 1000 / words).toFixed(2);
const share = (fn) => (100 * all.filter(fn).length / all.length).toFixed(1) + '%';
const openers = {}; for (const s of all) { const w = (s.split(' ')[0] || '').toLowerCase().replace(/^[“"(]/, '').replace(/[,.]$/, ''); if (w) openers[w] = (openers[w] || 0) + 1; }
const topOpeners = Object.entries(openers).sort((a, b) => b[1] - a[1]).slice(0, 12).map(([w, n]) => `${w} (${(100 * n / all.length).toFixed(1)}%)`).join(', ');
const byEra = {};
for (const p of essays) { const y = Number(p.url.slice(1, 5)); const era = y <= 2010 ? '2005–2010' : y <= 2016 ? '2011–2016' : y <= 2019 ? '2017–2019' : y <= 2022 ? '2021–2022' : '2024–2026'; const e = byEra[era] ||= { n: 0, sent: [], words: 0 }; e.n++; e.words += bodyText(p).split(' ').length; e.sent.push(...sentsOf(bodyText(p)).map((s) => s.split(' ').length)); }
const eraRows = Object.entries(byEra).map(([era, e]) => { const s = e.sent.sort((a, b) => a - b); return `| ${era} | ${e.n} | ${Math.round(e.words / e.n)} | ${s[Math.floor(s.length / 2)]} | ${(100 * s.filter((x) => x <= 6).length / s.length).toFixed(0)}% |`; }).join('\n');
const phrases = [['and yet', /\bAnd yet\b/g], ['but, (sentence-initial with comma)', /(?:^|[.!?]\s+)But,/g], ['so, (sentence-initial)', /(?:^|[.!?]\s+)So,/g], ['rather, / rather than', /\b[Rr]ather\b/g], ['based upon', /\bbased upon\b/g], ['in order to', /\bin order to\b/g], ['be able to', /\bbe able to\b/g], ['one another', /\bone another\b/g], ['folks', /\bfolks\b/g], ['make meaning', /\bmak(?:e|es|ing) meaning\b/g], ['feel as though', /\bfeel(?:s|ing)? as though\b/g], ['so long as', /\bso long as\b/g], ['I want', /\bI want\b/g], ['I believe', /\bI believe\b/g], ['I think', /\bI think\b/g], ['I am (uncontracted)', /\bI am\b/g], ["I'm", /\bI[’']m\b/g], ['incredible/incredibly', /\bincredibl[ey]\b/g], ['to be clear / for the record', /\b(?:To be clear|For the record)\b/g], ['and yet / but / so openers', /(?:^|[.!?]\s+)(?:And|But|So|Yet)\b/g]];
const phraseRows = phrases.map(([label, re]) => `| ${label} | ${per1k(re)} |`).join('\n');
const stats = `# Voice statistics

Measured over ${essays.length} essays (posts of 250+ words; ${words.toLocaleString()} words, ${all.length.toLocaleString()} sentences) by \`scripts/build-voice-corpus.js\` on ${new Date().toISOString().slice(0, 10)}. Short link posts and tweets are excluded; typewritten pages count through their transcripts.

## Rhythm

| Measure | Value |
|---|---|
| Sentence length: median / p10 / p90 | ${pct(0.5)} / ${pct(0.1)} / ${pct(0.9)} words |
| Sentences of 6 words or fewer | ${share((s) => s.split(' ').length <= 6)} |
| Sentences of 30 words or more | ${share((s) => s.split(' ').length >= 30)} |
| Questions | ${share((s) => s.endsWith('?'))} |
| Exclamations | ${share((s) => s.endsWith('!'))} |
| Sentences opening with And / But / So / Yet | ${share((s) => /^(And|But|So|Yet)\b/.test(s))} |
| Most common first words | ${topOpeners} |

## By era

| Era | Essays | Words / essay | Median sentence | Sentences ≤ 6 words |
|---|---|---|---|---|
${eraRows}

## Person and punctuation (per 1,000 words)

| Marker | Rate |
|---|---|
| I | ${per1k(/\bI\b/g)} |
| we / our | ${per1k(/\b(?:[Ww]e|[Oo]ur)\b/g)} |
| you / your | ${per1k(/\b[Yy]ou(?:r)?\b/g)} |
| colon before a list or a turn | ${per1k(/:\s/g)} |
| parenthetical aside | ${per1k(/\(/g)} |
| em dash | ${per1k(/—|--/g)} |
| semicolon | ${per1k(/;/g)} |
| scare quotes (“…”) | ${per1k(/“/g)} |
| contractions | ${per1k(/\b\w+n[’']t\b|\b(?:I[’']m|I[’']ve|I[’']d|I[’']ll|it[’']s|that[’']s|there[’']s|we[’']re|they[’']re|you[’']re)\b/g)} |

## Signature phrases (per 1,000 words)

| Phrase | Rate |
|---|---|
${phraseRows}
`;

console.log(stats);
console.log(`\n${typed.length} transcripts, ${essays.length} essays`);
if (APPLY) {
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'typewriter-transcripts.md'), transcripts);
  fs.writeFileSync(path.join(OUT, 'stats.md'), stats);
  console.log('wrote docs/voice/typewriter-transcripts.md, docs/voice/stats.md');
} else console.log('Run again with --apply to write docs/voice/.');
